import { escapeInert } from "@devos/intake";
import type { Analysis } from "./analyze.js";

export interface RenderMeta {
  projectName: string;
  specVersion: number;
  specSha256: string;
  /** ISO date (YYYY-MM-DD) supplied by the caller so output is deterministic. */
  date: string;
}

const PRIORITY_LABEL = { must: "Must", should: "Should", could: "Could" } as const;

function inline(s: string): string {
  return escapeInert(s.replace(/\s+/g, " ").trim());
}

/** Render docs/requirements.md. Every piece of spec text is inert (ADR-0011 §2). */
export function renderRequirementsMd(a: Analysis, meta: RenderMeta): string {
  if (!/^[0-9a-f]{64}$/.test(meta.specSha256)) throw new TypeError("specSha256 must be 64 lower-case hex characters");
  if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.date)) throw new TypeError("date must be YYYY-MM-DD");
  if (!Number.isInteger(meta.specVersion) || meta.specVersion < 1) throw new TypeError("specVersion must be a positive integer");

  const qByReq = new Map<string, string>();
  for (const q of a.openQuestions) if (q.requirement) qByReq.set(q.requirement, q.id);

  const out: string[] = [];
  out.push(`# Requirements — ${inline(meta.projectName)}`, "");
  out.push(
    `Generated by the DevOS Analyst from spec version ${meta.specVersion} (SHA-256 \`${meta.specSha256}\`) on ${meta.date}. ` +
      `Spec IDs are kept; IDs marked _assigned_ were added by the Analyst; items marked _proposed_ came from the model pass and cite their spec text. KK approves this file once.`,
    "",
  );

  out.push("## Requirements", "");
  if (a.requirements.length === 0) out.push("_No requirements found in the spec._", "");
  for (const r of a.requirements) {
    out.push(`### ${escapeInert(r.key)} — ${inline(r.title) || "_untitled_"}`, "");
    const facts = [`Priority: ${PRIORITY_LABEL[r.priority]}`];
    if (r.milestone) facts.push(`Milestone: ${inline(r.milestone)}`);
    if (r.assigned) facts.push("_assigned_");
    if (r.proposed) facts.push("_proposed by the model pass, check it_");
    else if (r.modelCriteria) facts.push("_criteria proposed by the model pass, check them_");
    out.push(facts.join(" · "), "");
    if (r.acceptance.length === 0) out.push(`_No acceptance criteria — see ${qByReq.get(r.key) ?? "open questions"}._`, "");
    else {
      out.push("Acceptance criteria:", "");
      for (const c of r.acceptance) out.push(`- ${inline(c)}`);
      out.push("");
    }
  }

  out.push("## Milestones", "");
  if (a.milestones.length === 0) out.push("_None stated._", "");
  else {
    for (const m of a.milestones) out.push(`${m.ordinal}. ${inline(m.name)}`);
    out.push("");
  }

  out.push("## Stack", "");
  if (a.stack.length === 0) out.push("_Not stated in the spec; the Architect proposes it._", "");
  else {
    for (const s of a.stack) out.push(`- ${inline(s.text)}`);
    out.push("");
  }

  out.push("## Open questions", "");
  if (a.openQuestions.length === 0) out.push("_None._", "");
  else {
    for (const q of a.openQuestions) out.push(`- **${q.id}** ${inline(q.text)}`);
    out.push("");
  }

  out.push("## Out of scope", "");
  if (a.outOfScope.length === 0) out.push("_None stated._", "");
  else {
    for (const o of a.outOfScope) out.push(`- ${escapeInert(o.key)} — ${inline(o.title)}`);
    out.push("");
  }

  return out.join("\n");
}
