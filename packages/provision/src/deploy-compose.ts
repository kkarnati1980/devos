// M2.4-c2c2 (docs/modules/M2.4.md, "M2.4-c2c2 decisions"): the S4-hardened, port-published Compose of each
// environment is committed to the project repo as `deploy/compose.<env>.devos.yaml`, so a git-based Coolify
// application that re-reads the repo on deploy still runs the hardened file. One commit on `main` through the Git Data
// API (blobs → tree → commit → fast-forward, `force:false`). Re-run: byte-equal files commit nothing; a different
// existing file is `compose_drift`, non-retryable, never overwritten.

import { stringify } from "yaml";
import { COMPOSE_PATH, HOOK_TIMEOUT_MS, hookEnvName, parseCompose, publishTailnetPort, isTailnetIpv4, type ApplicationOptions } from "./application.js";
import { CoreRepo } from "./core-repo.js";
import type { GitHubClient } from "./github.js";
import { ProviderError } from "./http.js";
import { blobSha } from "./repo-content.js";
import { StepError, type Found, type ProvisionStore, type StepSpec } from "./runner.js";
import { STACK_ENVS, type StackEnv } from "./stack.js";

const SLUG_RE = /^[a-z0-9][a-z0-9-]{0,62}$/;
const PORT_RE = /^[1-9]\d{3,4}$/;
const SHA_RE = /^[0-9a-f]{40}$/;
export const DEPLOY_COMPOSE_STEP = "github/deploy_compose";
/** Where an environment's generated Compose lives in the project repo; Coolify's `docker_compose_location` adds a `/`. */
export const deployComposePath = (env: StackEnv): string => `deploy/compose.${env}.devos.yaml`;
export const DEPLOY_COMPOSE_HEADER =
  "# Generated by DevOS (M2.4-c2c2): the S4-hardened Compose for this environment.\n" +
  "# Do not edit by hand: DevOS regenerates it and refuses to replace a changed copy.\n";

/**
 * The bytes of one environment's deploy Compose: the core `compose.yaml` at the `github/core` commit, hardened by S4's
 * `afterStack` hook (bounded; a refusal or a hang creates nothing), then the tailnet port published on `app` only.
 */
export async function generateDeployCompose(
  repo: CoreRepo, p: { id: string; slug: string }, env: StackEnv, coreCommit: string, port: number, opts: ApplicationOptions,
): Promise<Buffer> {
  const entry = (await repo.treeOf(coreCommit)).get(COMPOSE_PATH);
  if (!entry) throw new Error("compose-missing: the core commit has no compose.yaml");
  const compose = parseCompose(await repo.blobContent(entry.sha));
  const ms = opts.hookTimeoutMs ?? HOOK_TIMEOUT_MS;
  let timer: NodeJS.Timeout | undefined;
  const hardened = await Promise.race([
    opts.hooks.afterStack({ id: p.id, slug: p.slug }, { name: hookEnvName(env), port, portRangeStart: opts.range.from, compose }),
    new Promise<never>((_, rej) => { timer = setTimeout(() => rej(new StepError(DEPLOY_COMPOSE_STEP, "provider_error", true, true, `afterStack hook did not finish within ${ms} ms`)), ms); }),
  ]).finally(() => clearTimeout(timer));
  if (!hardened || typeof hardened.compose !== "object" || hardened.compose === null || Array.isArray(hardened.compose)) throw new Error("after-stack-no-compose");
  // Codex PR76-r4: the allocated port must reach the application, or the tailnet address leads nowhere.
  const published = publishTailnetPort(hardened.compose, port, opts.tailnetIp);
  return Buffer.from(DEPLOY_COMPOSE_HEADER + stringify(published), "utf8");
}

/**
 * The `github/deploy_compose` step: after `github/core` and the ports, before the applications. External id: the
 * commit on `main` that holds both files. Journalled but not an inventory row (`inventory: false`): the files go with
 * the repo. Inputs come only from this project's `done` journal rows; a missing row fails before any call.
 */
export function deployComposeStep(gh: GitHubClient, store: ProvisionStore, p: { id: string; slug: string }, opts: ApplicationOptions): StepSpec {
  if (!SLUG_RE.test(p.slug)) throw new Error("slug-invalid");
  if (typeof opts.tailnetIp !== "string" || !isTailnetIpv4(opts.tailnetIp)) throw new Error("tailnet-ip-invalid");
  if (!opts.hooks || typeof opts.hooks.afterStack !== "function") throw new Error("provision-hooks-required: afterStack (S4) must be registered");
  const repo = new CoreRepo(gh.http, opts.owner, `devos-${p.slug}`);
  const name = `${opts.owner}/devos-${p.slug}@main:deploy/`;
  /** The blob ids generated by this run's create, so the runner's follow-up lookup can confirm the push. */
  let expected: Map<string, string> | null = null;

  const done = async (key: string, err: string): Promise<string> => {
    const s = await store.getStep(p.id, key);
    if (s?.status !== "done" || !s.externalId) throw new Error(err);
    return s.externalId;
  };

  /** `main`'s head and tree; an empty or missing `main` is inconclusive here (the core step has run). */
  const mainTree = async (): Promise<{ head: string; tree: Map<string, { mode: string; sha: string }> }> => {
    const head = await repo.mainHead();
    if (head === null || head === "empty") throw new ProviderError("github", "bad-response", "github main is missing after the core push");
    return { head, tree: await repo.treeOf(head) };
  };

  const matches = (tree: Map<string, { mode: string; sha: string }>, want: Map<string, string>): boolean =>
    [...want].every(([path, id]) => tree.get(path)?.sha === id && tree.get(path)?.mode === "100644");

  return {
    key: DEPLOY_COMPOSE_STEP,
    provider: "github",
    kind: "deploy_compose",
    name,
    action: "provision.github.deploy_compose",
    inventory: false,
    lookup: async () => {
      // Without this run's generated bytes there is nothing to compare with: create compares and commits nothing
      // when the files are already byte-equal, so a fresh lookup defers to it.
      if (!expected) return null;
      const { head, tree } = await mainTree();
      return matches(tree, expected) ? { externalId: head, name, owned: true } : null;
    },
    create: async (): Promise<Found> => {
      const core = await done("github/core", "core-not-pushed");
      if (!SHA_RE.test(core)) throw new Error("core-commit-invalid");
      const files: { path: string; content: Buffer; sha: string }[] = [];
      for (const env of STACK_ENVS) {
        const port = await done(`coolify/port/${env}`, "port-not-allocated");
        if (!PORT_RE.test(port)) throw new Error("coolify-port-invalid");
        const content = await generateDeployCompose(repo, p, env, core, Number(port), opts);
        files.push({ path: deployComposePath(env), content, sha: blobSha(content) });
      }
      expected = new Map(files.map((f) => [f.path, f.sha]));

      const { head, tree } = await mainTree();
      for (const f of files) {
        const got = tree.get(f.path);
        if (got && (got.sha !== f.sha || got.mode !== "100644")) {
          throw new StepError(DEPLOY_COMPOSE_STEP, "compose_drift", false, true, `${f.path} on main differs from the Compose DevOS generates; it is not overwritten`);
        }
      }
      if (matches(tree, expected)) return { externalId: head, name, owned: true };

      // Pre-review: the tree is rebuilt from blob entries only; a submodule or other non-blob mode is refused, not mangled.
      for (const [path, e] of tree) {
        if (!/^100(644|755)$|^120000$/.test(e.mode)) throw new Error(`repo-entry-unsupported: ${path} has mode ${e.mode}`);
      }
      await store.assertLockHeld(p.id);
      for (const f of files) await repo.createBlob({ path: f.path, mode: "100644", content: f.content, sha: f.sha });
      const entries = [...tree].filter(([path]) => !expected!.has(path)).map(([path, e]) => ({ path, mode: e.mode, sha: e.sha }));
      for (const f of files) entries.push({ path: f.path, mode: "100644", sha: f.sha });
      const t = await repo.createTreeEntries(entries);
      const commit = await repo.createCommit("DevOS: hardened deploy Compose (preview, production)", t, [head]);
      // The reads, the hook and the writes above are awaits after the last lock check: check again before the ref moves.
      await store.assertLockHeld(p.id);
      await repo.fastForwardMain(commit);
      const after = await mainTree();
      // A stale read right after the write is transient: the runner looks up again and adopts (core-repo pattern).
      if (after.head !== commit || !matches(after.tree, expected)) throw new ProviderError("github", "network", "github main not yet showing the deploy Compose commit");
      return { externalId: commit, name, owned: true };
    },
  };
}
